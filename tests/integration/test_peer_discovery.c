/* test_peer_discovery.c -- 2.3's peer discovery: what a node is TOLD about its
 * mesh, and what it is allowed to DO with it.
 *
 * docs/SERVER_DESIGN.md 2.3 ("Peer discovery and auto-scale stay Phase 9"), 8
 * ("peers and their FSM states must be dumpable") and the Phase 9 item this
 * test is the acceptance for: ADVERTISE, and a SHUTDOWN that is a goodbye rather
 * than a failure.
 *
 * This file replaces a ten-line placeholder in tests/loadbal/ that returned 77
 * and said "load-balancer peer discovery is not implemented". The CTest name is
 * unchanged (`PeerDiscovery`) -- see irc_ctest_name() in
 * tests/integration/CMakeLists.txt for why a moved test must not be renamed, and
 * tests/known_skips.txt for the ratchet that enforces it.
 *
 * ---------------------------------------------------------------------------
 * FOUR CLAIMS, AND WHERE EACH ONE IS ASSERTED
 * ---------------------------------------------------------------------------
 *   1. AN ADVERTISED DIAL HINT IS NEVER DIalled. server_t::advs is a store a peer
 *      writes and only a log reads; this is the SSRF claim, and it is asserted
 *      on the THIRD NODE rather than on a log line (see the next block).
 *   2. A CLEAN LEAVE IS NOT A FAILURE. fed_shutdown: ... retried=0, and -- the
 *      half with teeth -- the count of link_dial: lines on the departing link.
 *   3. AN ADVERTISE REQUIRES AN ESTABLISHED LINK. fed_preauth_drop:
 *      ... command=ADVERTISE state=PENDING, counted in fed_preauth_drop=.
 *   4. THE LOAD FIGURE PROPAGATES, in BOTH directions: what a peer sends is
 *      observed here (fed_advertise: ... load=37%), and what this node sends is
 *      read off this test's own socket (ADVERTISE 0). The outbound half is a ZERO
 *      and says why -- see LOAD_OUT_TEXT, which is the honest reading of a knob
 *      this build cannot turn.
 *
 * ---------------------------------------------------------------------------
 * WHY CLAIM 1 NEEDS A THIRD NODE, AND WHY TWO NODES COULD NOT CARRY IT
 * ---------------------------------------------------------------------------
 * The obvious two-node version is: peer irc.b advertises a name and an address,
 * and the test checks that node irc.a did not dial. That test is VACUOUS, and it
 * is vacuous for a structural reason rather than a subtle one. A two-node mesh
 * has exactly one address in it -- the one the two nodes are talking on -- so an
 * advertisement that "points somewhere else" has nowhere else to point, and the
 * only thing the observer could check is its own log. A log line is the GUARD
 * TALKING ABOUT ITSELF; a guard that printed `dialed=NO` and then dialled anyway
 * would sail past it. The same trap closed three times in this project already
 * (tests/integration/test_nick_duplicate.c documents the fourth instance, where a
 * two-node fixture could not tell "the server you named is not the holder" from
 * "the server you named is not a peer I can reach"), so the shape here is fixed:
 *
 *   irc.a   the node under test. It has EXACTLY ONE configured peer, irc.b.
 *   irc.b   THIS TEST, on a socket the test owns, so the payload is exact.
 *   irc.c   a real node with NO peers at all, and the target of the hint.
 *
 * irc.c is what makes the claim falsifiable. It is a listening node on a real
 * ephemeral port, so if the learned name ever reached the dial path the kernel
 * would complete a connection and irc.c would print `client_connect:` and
 * accepted=1. It has no peers, so `link_established:` on it is unambiguously
 * somebody dialling it out of nothing. And irc.a's own link set has no entry for
 * irc.c, so "the hint named something this node is not configured with" is a
 * statement about the link table rather than about a guess.
 *
 * ---------------------------------------------------------------------------
 * WHY THE PEER IS A RAW SOCKET (this file's irc.b) RATHER THAN A SECOND NODE
 * ---------------------------------------------------------------------------
 * Because a second node built from THIS code cannot produce the payloads the
 * claims are about. A real node's ADVERTISE is generated by fed_send_advertise()
 * from its own configuration, so it can only ever advertise a name and address
 * the operator gave it; it cannot be made to advertise irc.c at irc.c's port.
 * The same is true of SHUTDOWN: no node in this build ORIGINATES one at all
 * (fed_send_shutdown() has no caller -- server_shutdown() does not call it, so a
 * SIGTERM'd node says nothing and its peers time it out), which means the only
 * way to put a SHUTDOWN on a wire in a test is to write one. tests/integration/
 * test_fed_guards.c owns one end of a link for exactly the same reason and says
 * so at length; this file is the same technique applied to the two verbs of 2.3
 * rather than to the guard chain.
 *
 * What is NOT faked: the handshake is a real FEDERATE with the right name, the
 * right secret and the right version word, A's link goes through the real FSM,
 * and every line carries a 2.4 block produced by the node's own serialiser so
 * the guard chain above G10 is exercised rather than bypassed.
 *
 * ---------------------------------------------------------------------------
 * NO FIXED sleep() ANYWHERE (6.3)
 * ---------------------------------------------------------------------------
 * Every wait is a deadline: nf_expect()/nf_expect_u64() over a child's output,
 * or poll() with a deadline over this test's own socket. That is not only a style
 * rule here -- the claims are about TIMING (a retry that must not happen, a dial
 * that must not happen), so a test that slept a fixed second would be asserting
 * against a duration rather than against the node's behaviour.
 *
 * ---------------------------------------------------------------------------
 * THE TWO CLOCKS, AND WHY THEY ARE THE NODE'S AND NOT THIS TEST'S
 * ---------------------------------------------------------------------------
 * Two claims are absences, and an absence needs a window, and the window must be
 * the node's own clock rather than how fast this test can issue commands:
 *
 *   CLAIM 1's window is irc.a's T3 KEEPALIVE, shortened per process to 80 ms by
 *   fed_set_timeouts(). The test then reads N of those PINGs off its own socket.
 *   Each one is a tick of irc.a's, so N of them is N x 80 ms of irc.a running
 *   with the hint in its store -- and a keepalive is the cheapest line this tree
 *   can put on a peer link.
 *
 *   CLAIM 2's window is irc.d's T3 KEEPALIVE at 60 ms. irc.d's PINGs arrive at
 *   irc.a as INBOUND lines, so `lines=` on irc.a climbs on a real timer, and
 *   nf_expect_u64_ge(&a, "lines=", ...) is a deadline wait over that timer.
 *
 * AND THE BOUNDARY IS FAULT-INDEPENDENT IN BOTH CASES, which is the property that
 * makes the two windows worth having rather than decorative. Case 1's boundary is
 * irc.d's CLIENT lines -- inbound, and something a dial never produces -- and case
 * 2's is irc.d's keepalives, which likewise arrive as inbound lines. A boundary
 * measured on the very thing being asserted (irc.a's `accepted=`, or its
 * `link_dial:` count) would be satisfied BY the fault and would stop before it.
 *
 * The two other numbers that are shortened are named where they are set, with the
 * reason. What is NOT shortened anywhere: the ORDER of the guard chain, the
 * contents of the advertisement store, the shape of the retry ladder (base
 * doubled, capped, bounded by a budget that reports), and the single T7 condition
 * that refuses a diallable link. Those are the claims.
 */
